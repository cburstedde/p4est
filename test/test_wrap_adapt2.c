#include<p4est_mesh.h>
#include<p4est_wrap.h>
#include<p4est_extended.h>
#include<p4est_iterate.h>

typedef struct mesh_data
{
  int treeid;
  int x;
  int y;
  int level;
} mesh_data_t;
static mesh_data_t *get_initial_mesh();
static mesh_data_t *get_target_mesh();

int quadrants_overlap(p4est_iter_volume_info_t * info, mesh_data_t *target)
{
  int target_length = P4EST_QUADRANT_LEN (target->level);

  return info->treeid == target->treeid &&
         info->quad->x >= target->x &&
         info->quad->x < target->x + target_length &&
         info->quad->y >= target->y &&
         info->quad->y < target->y + target_length;
}

typedef struct mark_patches_data
{
  p4est_wrap_t *pp;
  mesh_data_t *curr;
  mesh_data_t *end;
  int verbose;
} mark_patches_data_t;

static void
mark_patches_cb (p4est_iter_volume_info_t * info,
                 void *user_data)
{
  mark_patches_data_t *data = (mark_patches_data_t *) user_data;
  while(!quadrants_overlap(info, data->curr))
  {
    data->curr++;
    if (data->curr == data->end)
    {
      SC_ABORT("No more quadrants to check");
    }
  }
  int target_level = data->curr->level;
  if(target_level > info->quad->level)
  {
    p4est_wrap_mark_refine (data->pp, info->treeid, info->quadid);
    if(data->verbose)
      printf("Makring tree %d quadrant %d for refinement\n", info->treeid, info->quadid);
  }
  else if (target_level < info->quad->level)
  {
    p4est_wrap_mark_coarsen (data->pp, info->treeid, info->quadid);
    if(data->verbose)
      printf("Marking tree %d quadrant %d for coarsening\n", info->treeid, info->quadid);
  }
}

static void
mark_patches (p4est_wrap_t *pp, mesh_data_t *mesh, int verbose)
{
  mark_patches_data_t data;
  data.pp = pp;
  data.curr = &mesh[0];
  data.end = &mesh[164];
  data.verbose = verbose;
  p4est_iterate (pp->p4est, NULL, &data, mark_patches_cb, NULL, NULL);
}

int
main (int argc, char **argv)
{
  int                 num_errors = 0;
  sc_MPI_Comm         mpicomm = sc_MPI_COMM_SELF;
  p4est_connectivity_t *conn;
  p4est_wrap_t        *wrap;
  p4est_wrap_params_t params;
  mesh_data_t *initial_mesh = get_initial_mesh();
  mesh_data_t *target_mesh = get_target_mesh();

  sc_MPI_Init (&argc, &argv);
  sc_init (mpicomm, 1, 1, NULL, SC_LP_DEFAULT);
  p4est_init (NULL, SC_LP_DEFAULT);

  /* create a 2x2 brick that is uniformly refined to level 2 except for a level 1
   * quadrant with coordinates (0,0,0) in tree 3. At the edges of the coarse
   * quadrant there are edgehanging-corner neighbors inside the tree as well as
   * across tree faces and edges. */
  conn = p4est_connectivity_new_disk(0,0);

  p4est_wrap_params_init (&params); 
  params.hollow = 0; 
  wrap = p4est_wrap_new_params (mpicomm, conn, 0, &params);

  for(int i = 0; i < 3; i++)
  {
    mark_patches(wrap, initial_mesh, 0);
    SC_CHECK_ABORT(p4est_wrap_adapt (wrap), "Expected p4est_wrap_adapt to return true");
    if(p4est_wrap_partition(wrap, 0, NULL, NULL, NULL))
      p4est_wrap_complete(wrap);
  }

  SC_CHECK_ABORT(wrap->p4est->global_num_quadrants == 164, "wrap->p4est->global_num_quadrants != 164");

  printf("-----------------------\n");
  printf("Adapting to target mesh\n");
  printf("-----------------------\n");
  mark_patches(wrap, target_mesh, 1);
  SC_CHECK_ABORT(p4est_wrap_adapt (wrap), "Expected p4est_wrap_adapt to return true");
  SC_CHECK_ABORT(wrap->p4est->global_num_quadrants == 164, "wrap->p4est->global_num_quadrants != 164");

  p4est_wrap_destroy (wrap);
  //p4est_connectivity_destroy (conn);

  sc_finalize ();
  sc_MPI_Finalize ();

  return num_errors;
}

